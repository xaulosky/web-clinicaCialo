CREATE TABLE IF NOT EXISTS events (
    id VARCHAR(36) NOT NULL,
    event_name VARCHAR(40) NOT NULL,
    anonymous_id VARCHAR(64) NOT NULL,
    session_id VARCHAR(64) NULL,
    user_id VARCHAR(36) NULL,
    path VARCHAR(255) NULL,
    treatment_id VARCHAR(100) NULL,
    treatment_category VARCHAR(80) NULL,
    search_term VARCHAR(150) NULL,
    results_count INT NULL,
    referrer VARCHAR(255) NULL,
    utm_source VARCHAR(100) NULL,
    utm_medium VARCHAR(100) NULL,
    utm_campaign VARCHAR(100) NULL,
    utm_content VARCHAR(100) NULL,
    utm_term VARCHAR(100) NULL,
    device VARCHAR(20) NULL,
    country VARCHAR(2) NULL,
    value_clp INT NULL,
    order_id VARCHAR(36) NULL,
    user_agent VARCHAR(255) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    INDEX idx_event_created (event_name, created_at),
    INDEX idx_anon (anonymous_id),
    INDEX idx_session (session_id),
    INDEX idx_treatment (treatment_id),
    INDEX idx_path (path),
    INDEX idx_utm (utm_source, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
